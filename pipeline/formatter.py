"""SRT 및 ASS(SubStation Alpha) 자막 파일 생성 및 타임스탬프 보정 모듈."""

from __future__ import annotations

import logging
from pathlib import Path
from typing import List

from pipeline.models import SubtitleSegment

logger = logging.getLogger(__name__)


def _format_srt_timestamp(seconds: float) -> str:
    """초 단위 시간을 SRT 타임스탬프(HH:MM:SS,mmm)로 변환합니다."""
    ms_total = max(0, int(round(seconds * 1000)))
    hours, rem = divmod(ms_total, 3_600_000)
    minutes, rem = divmod(rem, 60_000)
    secs, ms = divmod(rem, 1000)
    return f"{hours:02d}:{minutes:02d}:{secs:02d},{ms:03d}"


def _format_ass_timestamp(seconds: float) -> str:
    """초 단위 시간을 ASS 타임스탬프(H:MM:SS.cc)로 변환합니다."""
    cs_total = max(0, int(round(seconds * 100)))
    hours, rem = divmod(cs_total, 360_000)
    minutes, rem = divmod(rem, 6000)
    secs, cs = divmod(rem, 100)
    return f"{hours:d}:{minutes:02d}:{secs:02d}.{cs:02d}"


def normalize_timestamps(segments: List[SubtitleSegment]) -> List[SubtitleSegment]:
    """자막 간 타임스탬프 역전이나 겹침을 방지하고 최소 노출 시간을 보장합니다."""
    for i, seg in enumerate(segments):
        if seg.end <= seg.start:
            seg.end = seg.start + 1.2
        # 다음 자막 시작 시간과 겹치지 않도록 클램핑
        if i + 1 < len(segments) and seg.end > segments[i + 1].start:
            seg.end = max(seg.start + 0.3, segments[i + 1].start - 0.02)
    return segments


def write_srt(
    segments: List[SubtitleSegment],
    output_path: Path,
    bilingual: bool = False,
    use_original_only: bool = False,
) -> Path:
    """세그먼트 리스트를 표준 UTF-8 `.srt` 파일로 저장합니다."""
    segments = normalize_timestamps(segments)
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    blocks: List[str] = []
    for idx, seg in enumerate(segments, start=1):
        start_ts = _format_srt_timestamp(seg.start)
        end_ts = _format_srt_timestamp(seg.end)

        if use_original_only or not seg.translated_text:
            body = seg.original_text
        elif bilingual:
            body = f"{seg.translated_text}\n{seg.original_text}"
        else:
            body = seg.translated_text

        blocks.append(f"{idx}\n{start_ts} --> {end_ts}\n{body}\n")

    output_path.write_text("\n".join(blocks), encoding="utf-8-sig")
    logger.info("SRT 자막 저장 완료: %s", output_path)
    return output_path


def write_ass(
    segments: List[SubtitleSegment],
    output_path: Path,
    bilingual: bool = False,
) -> Path:
    """가독성 높은 그림자/외곽선 스타일이 적용된 `.ass` 자막 파일을 생성합니다."""
    segments = normalize_timestamps(segments)
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    header = """[Script Info]
; Generated by Local AI Movie Subtitle Generator
ScriptType: v4.00+
PlayResX: 1920
PlayResY: 1080
WrapStyle: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,맑은 고딕,56,&H00FFFFFF,&H000000FF,&H00000000,&H80000000,0,0,0,0,100,100,0,0,1,3,1.5,2,40,40,45,1
Style: OriginalSub,맑은 고딕,38,&H00B0E0E6,&H000000FF,&H00000000,&H80000000,0,0,0,0,100,100,0,0,1,2,1,2,40,40,35,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    lines = [header.strip()]
    for seg in segments:
        start_ts = _format_ass_timestamp(seg.start)
        end_ts = _format_ass_timestamp(seg.end)
        ko_text = (seg.translated_text or seg.original_text).replace("\n", r"\N")
        orig_text = seg.original_text.replace("\n", r"\N")

        if bilingual and seg.translated_text:
            combined = f"{ko_text}\\N{{\\rOriginalSub}}{orig_text}"
            lines.append(f"Dialogue: 0,{start_ts},{end_ts},Default,,0,0,0,,{combined}")
        else:
            lines.append(f"Dialogue: 0,{start_ts},{end_ts},Default,,0,0,0,,{ko_text}")

    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")
    logger.info("ASS 자막 저장 완료: %s", output_path)
    return output_path
